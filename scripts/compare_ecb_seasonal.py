"""Check the world CPI seasonal adjustment (#34) against the ECB's own adjustment.

The world CPI proxy is weighted quarterly log growth (download_data.chain_weighted_tv),
so a source-adjusted variant needs no other leg: from 1997Q2 it is the committed
unadjusted growth minus the renormalised euro-area weight times the ECB's seasonal
and calendar component (Eurostat unadjusted HICP growth minus ECB adjusted growth).
Reads only committed files and writes results/ecb_seasonal_check.md.

Not a production change: data/boe_var_data.csv is untouched. Expect an imperfect
match: the proxy's China leg is unadjusted, the ECB series is changing composition
and working-day adjusted, the proxy's euro-area leg is EA19, and before 1997 it is
the German backcast, which has no source-adjusted counterpart here.

Usage: python scripts/compare_ecb_seasonal.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from download_data import era_weights  # noqa: E402

OUT = ROOT / "results" / "ecb_seasonal_check.md"
LAST_FULL = "2025Q2"  # last quarter with all four world CPI legs
ERAS = [("1997Q2", "2004Q4"), ("2005Q1", "2014Q4"), ("2015Q1", "2021Q4"),
        ("2022Q1", "2025Q1"), ("1997Q2", "2025Q1")]


def quarterly(s: pd.Series) -> pd.Series:
    g = s.groupby(s.index.asfreq("Q")).agg(["mean", "count"])
    return g.loc[g["count"] == 3, "mean"]


def f_test(g: pd.Series, a: str, b: str):
    x = g.loc[pd.Period(a, "Q"):pd.Period(b, "Q")].dropna()
    return stats.f_oneway(*[x[x.index.quarter == k].values for k in (1, 2, 3, 4)])


def main() -> None:
    m = pd.read_csv(ROOT / "data/external/ecb_hicp_euro_area_monthly.csv")
    m.index = pd.PeriodIndex(m["month"], freq="M")
    sa, nsa = quarterly(m["hicp_sa_ecb"]), quarterly(m["hicp_nsa_eurostat"])
    seas = (100 * np.log(nsa)).diff() - (100 * np.log(sa)).diff()

    def load(name):
        d = pd.read_csv(ROOT / "data" / name)
        return d.set_index(pd.PeriodIndex(d["quarter"], freq="Q"))["world_cpi"]

    g_nsa = load("boe_var_data_world_cpi_nsa.csv").diff()
    g34 = load("boe_var_data.csv").diff()
    w_ea = pd.Series({p: era_weights(p)["ea"] / sum(era_weights(p).values()) for p in g_nsa.index})
    idx = g_nsa.dropna().index
    # All four legs carry the era weights from 1997Q2 (ECB start) to 2025Q2. After
    # that China (2025Q3) and Japan (2026Q1) drop out of world CPI and the weights
    # renormalise over fewer legs (data/README.md), so the window stops there.
    idx = idx[(idx >= pd.Period("1997Q2", "Q")) & (idx <= pd.Period(LAST_FULL, "Q"))
              & idx.isin(seas.dropna().index)]
    g_ecb = g_nsa.copy()
    g_ecb[idx] = g_nsa[idx] - w_ea[idx] * seas[idx]
    rem34, rem_ecb = (g_nsa - g34)[idx], (w_ea * seas)[idx]
    def yoy(g):
        return g.rolling(4).sum()

    gap = (yoy(g_ecb) - yoy(g34))[idx[3:]]
    gap_nsa_ecb = (yoy(g_ecb) - yoy(g_nsa))[idx[3:]]
    gap_nsa_34 = (yoy(g34) - yoy(g_nsa))[idx[3:]]

    L = ["# World CPI seasonal adjustment: #34's filter against the ECB's", "",
         "Generated by `scripts/compare_ecb_seasonal.py` from committed files: the unadjusted proxy "
         "(`data/boe_var_data_world_cpi_nsa.csv`), the adjusted proxy (`data/boe_var_data.csv`), and the "
         "ECB's working-day and seasonally adjusted euro-area HICP with Eurostat's unadjusted index "
         "(`data/external/ecb_hicp_euro_area_monthly.csv`; provenance in `data/external/README.md`). "
         f"Window {idx[0]}-{idx[-1]}, {len(idx)} quarters: from the ECB series' start to the last quarter "
         "in which all four legs of the proxy have data. Quarterly log growth, 100*log points.", "",
         "The ECB variant replaces only the euro-area leg's seasonal component (weight "
         f"{min(w_ea[idx]):.3f}-{max(w_ea[idx]):.3f}, renormalised over the four legs as in `TRADE_WEIGHT_ERAS`).", "",
         "## Seasonal gate (one-way F test of quarterly growth across the four quarters)", "",
         "| Era | Unadjusted F (p) | #34 F (p) | ECB variant F (p) |", "|---|---|---|---|"]
    for a, b in ERAS:
        cells = [f_test(g, a, b) for g in (g_nsa, g34, g_ecb)]
        L.append(f"| {a}-{b} | " + " | ".join(f"{c.statistic:.2f} ({c.pvalue:.3f})" for c in cells) + " |")
    L += ["", "## What each removes", "",
          f"- Correlation of the quarterly seasonal component removed by #34 with the ECB's (times the "
          f"euro-area weight): **{rem34.corr(rem_ecb):.3f}**. Standard deviation {rem34.std():.3f} against "
          f"{rem_ecb.std():.3f}; RMS difference {np.sqrt(((rem34 - rem_ecb) ** 2).mean()):.3f}.", "",
          "| Quarter | #34 mean removed | ECB mean removed | #34 since 2015 | ECB since 2015 |", "|---|---|---|---|---|"]
    since = pd.Period("2015Q1", "Q")
    for k in (1, 2, 3, 4):
        q = idx[idx.quarter == k]
        L.append(f"| Q{k} | {rem34[q].mean():+.3f} | {rem_ecb[q].mean():+.3f} | "
                 f"{rem34[q[q >= since]].mean():+.3f} | {rem_ecb[q[q >= since]].mean():+.3f} |")
    L += ["", "## Year-on-year world CPI inflation", "",
          f"- ECB variant minus #34: max {gap.abs().max():.3f}pp ({gap.abs().idxmax()}), RMS {np.sqrt((gap ** 2).mean()):.3f}pp.",
          f"- #34 minus unadjusted: max {gap_nsa_34.abs().max():.3f}pp; ECB variant minus unadjusted: max {gap_nsa_ecb.abs().max():.3f}pp.", "",
          "## Reading", "",
          "- Both adjustments pass the seasonal gate in every era, and they remove nearly the same pattern, "
          "including its drift (a larger Q2 effect since 2015). The source adjustment independently supports "
          "#34's finding that the unadjusted proxy carries a seasonal the VAR does not absorb.",
          "- The ECB's component is somewhat larger in amplitude (it also removes calendar effects, and the proxy's "
          "euro-area leg is the EA19 index, not the changing-composition euro area).",
          "- The production column is not switched: the gap in year-on-year inflation is small against the "
          "model's bands, a switch would need the German backcast and the China leg adjusted at source too, "
          "and it would regenerate every artefact. Revisit at the next data refresh.", ""]
    OUT.write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
