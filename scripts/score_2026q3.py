"""Score the stored 2026Q3 SVAR forecasts against the first published outturns.

Reads only committed files:
  data/external/uk_outturns_2026q3.csv        ONS / BoE outturns (provenance in data/external/README.md)
  data/external/svar_stored_forecasts_2026q3.csv   2026Q3 entries of the two archived site rounds
and writes results/score_2026q3.md. It never rewrites a stored forecast.

One quarter is one draw from each predictive distribution: this records where
the outturn fell, it is not evidence of forecast skill.

Usage: python scripts/score_2026q3.py
"""
from __future__ import annotations

import csv
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXT = ROOT / "data" / "external"
OUT = ROOT / "results" / "score_2026q3.md"

# BoE July 2026 MPR Table 3.B central projection for 2026Q3, as transcribed in
# results/forecast_vs_boe_obr.md (Part 1 and section 3.1).
BOE_JULY_2026Q3 = {"cpi": 2.9, "gdp": 1.1, "unemployment": 5.0}
# The 17 Nov 2026 run of scripts/run_external_comparison.py (data to 2026Q2,
# world CPI seasonally adjusted; results/forecast_vs_boe_obr.md, "Current run"):
# not archived before the outturns, so it is reported separately.
SVAR_17NOV_UNEMPLOYMENT = {"median": 4.87, "lo68": 4.69, "hi68": 5.05, "lo90": 4.59, "hi90": 5.18}


def outturns() -> dict[str, float]:
    rows = list(csv.DictReader(open(EXT / "uk_outturns_2026q3.csv")))
    v = {(r["code"], r["period"]): float(r["value"]) for r in rows}
    def cpi(y):
        return sum(v[("D7BT", f"{y}-{m:02d}")] for m in (7, 8, 9)) / 3

    return {
        "gdp": 100 * (v[("ABMI", "2026Q3")] / v[("ABMI", "2025Q3")] - 1),
        "cpi": 100 * (cpi(2026) / cpi(2025) - 1),
        "unemployment": 100 * v[("MGSC", "2026Q3")] / (v[("MGSC", "2026Q3")] + v[("MGRZ", "2026Q3")]),
        "unemployment_published": v[("MGSX", "2026Q3")],
        "bank_rate": v[("IUQABEDR", "2026Q3")],
    }


def where(x: float, f: dict) -> str:
    if f["lo68"] <= x <= f["hi68"]:
        return "inside 68%"
    if f["lo90"] <= x <= f["hi90"]:
        return "outside 68%, inside 90%"
    return "outside 90%"


def main() -> None:
    o = outturns()
    fc = list(csv.DictReader(open(EXT / "svar_stored_forecasts_2026q3.csv")))
    L = ["# 2026Q3: stored SVAR forecasts against the first outturns", "",
         "Generated by `scripts/score_2026q3.py` from committed files only. Four-quarter rates on the ONS "
         "series the forecasts target (CPI D7BT, GDP ABMI). Outturns below are simple rates, 100*(P_t/P_t-4 - 1). "
         "The 29 Jul round predates the 6 Nov 2026 basis correction and is on the log basis, 100*ln(P_t/P_t-4), "
         "(inferred from its units field and date), so it is scored against the outturn on that basis (column 'Outturn, same basis').", "",
         "## Outturns", "",
         f"- GDP (ABMI, ONS first quarterly estimate, 12 Nov 2026): **{o['gdp']:.2f}%**. The 2025Q1-2026Q2 "
         "levels in this release equal `data/boe_var_data.csv`, so no vintage is mixed.",
         f"- CPI (D7BT, mean of Jul-Sep against Jul-Sep 2025, ONS 18 Nov 2026): **{o['cpi']:.2f}%**.",
         f"- Unemployment (16+, MGSC / (MGSC + MGRZ), ONS LMS 17 Nov 2026): **{o['unemployment']:.2f}%** "
         f"(published to one decimal as {o['unemployment_published']:.1f}%).",
         f"- Bank Rate (IUQABEDR, quarterly average): {o['bank_rate']:.2f}%.", "",
         "## Stored forecasts (archived site rounds, unchanged)", "",
         "| Round (data edge, archived) | Variable | Basis | Median | 68% | 90% | Outturn, same basis | Error (out - median) | Where |",
         "|---|---|---|---|---|---|---|---|---|"]
    for r in fc:
        f = {k: float(r[k]) for k in ("median", "lo68", "hi68", "lo90", "hi90")}
        log = r["basis"].startswith("log")
        x = 100 * math.log1p(o[r["variable"]] / 100) if log else o[r["variable"]]
        L.append(f"| {r['round']} ({r['data_edge']}, {r['archived_utc'][:16].replace('T', ' ')} UTC) | "
                 f"{r['variable'].upper()} | {'log' if log else 'simple'} | {f['median']:.2f} | {f['lo68']:.2f}-{f['hi68']:.2f} | "
                 f"{f['lo90']:.2f}-{f['hi90']:.2f} | {x:.2f} | {x - f['median']:+.2f} | {where(x, f)} |")
    u = SVAR_17NOV_UNEMPLOYMENT
    L += ["", "Sources: " + "; ".join(sorted({r["source"] for r in fc})) + ".", "",
          "Both rounds are out of sample: the 29 Jul round's data end in 2026Q1, the 12 Nov round's in 2026Q2. "
          "The 12 Nov round was archived at 05:13 UTC on the day ONS published the GDP first estimate, and after "
          "the September CPI release (21 Oct), which the model's data did not include. It was produced before the "
          "world CPI seasonal adjustment (#34).", "",
          "## Not archived before the outturns (reported separately)", "",
          f"- Unemployment, 17 Nov 2026 run (Okun satellite, data to 2026Q2): median {u['median']:.2f}%, "
          f"68% {u['lo68']:.2f}-{u['hi68']:.2f}, 90% {u['lo90']:.2f}-{u['hi90']:.2f}. Outturn {o['unemployment']:.2f}%: "
          f"{where(o['unemployment'], u)}, {o['unemployment'] - u['lo90']:+.2f}pp from the 90% lower edge. "
          "The site rounds store no unemployment forecast.", "",
          "## BoE July 2026 MPR, same quarter (benchmark)", "",
          "A modal projection conditioned on the market Bank Rate curve, made in July on the pre-Blue Book 2026 "
          "vintage of GDP history, so its GDP error mixes a forecast miss with a data revision. Context, not a race.", "",
          "| Variable | BoE central | Outturn | Error |", "|---|---|---|---|"]
    for k in ("cpi", "gdp", "unemployment"):
        L.append(f"| {k.upper() if k != 'unemployment' else 'Unemployment'} | {BOE_JULY_2026Q3[k]:.1f} | "
                 f"{o[k]:.2f} | {o[k] - BOE_JULY_2026Q3[k]:+.2f} |")
    L += ["", "## Scope", "",
          "- Only the UK legs are scored. World GDP, world CPI and oil are built from FRED and OECD series "
          "(`data/README.md`), outside the publishers approved for this download (ONS, BoE, ECB/Eurostat, Destatis).",
          "- One quarter is one draw from each predictive distribution. It says where the outturn fell, "
          "nothing about calibration or skill; the backtest in `results/coverage_evaluation.json` is the evidence for that.",
          "- First estimates revise. Re-score when ONS revises 2026Q3.", ""]
    OUT.write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
